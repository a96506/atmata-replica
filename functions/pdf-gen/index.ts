function pageHeader(title: string, companyName: string, isAr: boolean) {
  return {
    left: isAr ? '' : companyName,
    center: '',
    right: isAr ? companyName : title,
  };
}

function pageFooter(footerText: string) {
  return { left: footerText, right: 'Page {page} of {pages}' };
}

async function renderDoc(docType: string, data: DocData, locale: PdfLocale): Promise<Uint8Array> {
  const L = labelsFor(locale);
  const isAr = locale === 'ar';
  const title = `${docTypeLabel(docType, locale)} ${data.number}`;
  const blocks = buildDocBlocks(docType, data, L, locale);
  const fontEntries = await loadLocaleFonts(locale);
  const layout: Partial<PdfLayoutOptions> = {
    direction: isAr ? 'r2l' : 'l2r',
    tagged: 'pdfa2b',
    colors: BW_COLORS,
    headerTemplate: pageHeader(title, data.companyName, isAr),
    footerTemplate: pageFooter(L.footer),
  };
  return buildDocumentPDFBytes(
    { docTitle: title, title, blocks, footerText: L.footer, fontEntries },
    layout,
  );
}

async function renderFinancial(data: FinancialData, locale: PdfLocale): Promise<Uint8Array> {
  const L = labelsFor(locale);
  const isAr = locale === 'ar';
  const title = `${data.statementType} — ${data.period}`;
  const blocks = buildFinancialBlocks(data, L, locale);
  const fontEntries = await loadLocaleFonts(locale);
  const layout: Partial<PdfLayoutOptions> = {
    direction: isAr ? 'r2l' : 'l2r',
    tagged: 'pdfa2b',
    colors: BW_COLORS,
    headerTemplate: pageHeader(title, data.companyName, isAr),
    footerTemplate: pageFooter(L.footer),
  };
  return buildDocumentPDFBytes(
    { docTitle: title, title, blocks, footerText: L.footer, fontEntries },
    layout,
  );
}

// ─── data fetch (RLS-scoped via user token) ───────────────────────────────

type SdkClient = ReturnType<typeof createClient>;

class FunctionFailure extends Error {
  constructor(
    readonly code: 'NOT_FOUND' | 'CONFLICT' | 'STORAGE_FAILED' | 'UNAVAILABLE' | 'INTERNAL',
    readonly status: number,
    readonly retryable = false,
  ) {
    super(code);
  }
}

function camelize<T = Record<string, unknown>>(row: T): T {
  const out: Record<string, unknown> = {};
  for (const k of Object.keys(row)) {
    const camel = k.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
    out[camel] = row[k];
  }
  return out as T;
}

async function fetchOne<T = Record<string, unknown>>(
  c: SdkClient,
  table: string,
  id: string,
  select: string,
): Promise<T> {
  const { data, error } = await c.database
    .from(table)
    .select(select)
    .eq('id', id)
    .single();
  if (error || !data) throw new FunctionFailure('NOT_FOUND', 404);
  return camelize(data as T);
}

async function fetchLines(
  c: SdkClient,
  lineTable: string,
  parentCol: string,
  docId: string,
): Promise<LineRow[]> {
  const { data, error } = await c.database
    .from(lineTable)
    .select('product_id, description, qty, qty_delivered, unit_price')
    .eq(parentCol, docId);
  if (error) throw new FunctionFailure('UNAVAILABLE', 503, true);
  const rows = data ?? [];
  const productIds = [...new Set(rows.map((row: Record<string, unknown>) => String(row.product_id ?? '')).filter(Boolean))];
  const productMap = new Map<string, { sku?: string; name?: string }>();
  if (productIds.length > 0) {
    const { data: products, error: productError } = await c.database
      .from('products')
      .select('id, sku, name')
      .in('id', productIds);
    if (productError) throw new FunctionFailure('UNAVAILABLE', 503, true);
    for (const product of products ?? []) {
      productMap.set(String(product.id), product as { sku?: string; name?: string });
    }
  }
  return rows.map((r: Record<string, unknown>) => {
    const row = camelize(r);
    const product = productMap.get(String(row.productId ?? ''));
    const qty = Number(row.qtyDelivered ?? row.qty ?? 0);
    const unitPrice = Number(row.unitPrice ?? 0);
    return {
      code: String(product?.sku ?? ''),
      description: String(row.description ?? product?.name ?? ''),
      qty,
      unitPrice,
      total: Number((row.total ?? qty * unitPrice).toFixed(3)),
    };
  });
}

