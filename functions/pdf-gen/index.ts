async function fetchDocData(c: SdkClient, docType: Exclude<DocType, 'financial'>, docId: string): Promise<DocData> {
  const docTable = DOC_TABLEL[docType];
  const lineTable = LINE_TABLEL[docType];
  const parentCol = LINE_PARENT_COL[docType];
  const partyTable = PARTY_TABLEL[docType];

  const doc = await fetchOne<Record<string, unknown>>(c, docTable, docId, '*');

  const [party, company, lines] = await Promise.all([
    fetchOne<Record<string, unknown>>(c, partyTable, String(doc.customerId ?? doc.supplierId ?? ''), 'id, name, vat_number'),
    fetchOne<Record<string, unknown>>(c, 'companies', String(doc.companyId ?? ''), 'id, name, vat_number, base_currency'),
    fetchLines(c, lineTable, parentCol, docId),
  ]);

  return {
    companyId: String(company.id ?? ''),
    number: String(doc.number ?? ''),
    date: String(doc.date ?? ''),
    dueDate: doc.dueDate ? String(doc.dueDate) : undefined,
    validUntil: doc.validUntil ? String(doc.validUntil) : undefined,
    partyType: PARTY_TABLEL[docType] === 'suppliers' ? 'supplier' : 'customer',
    partyName: String(party.name ?? ''),
    partyVat: party.vatNumber ? String(party.vatNumber) : undefined,
    companyName: String(company.name ?? ''),
    companyVat: company.vatNumber ? String(company.vatNumber) : undefined,
    currency: String(doc.currency ?? company.baseCurrency ?? 'KWD'),
    lines,
    subtotal: Number(doc.subtotal ?? 0),
    taxTotal: Number(doc.taxTotal ?? 0),
    total: Number(doc.total ?? 0),
    notes: doc.notes ? String(doc.notes) : undefined,
    state: String(doc.state ?? 'draft'),
  };
}

async function fetchFinancialData(
  c: SdkClient,
  type: FinancialType,
  opts: {
    periodId?: string;
    accountId?: string;
    from?: string;
    to?: string;
  },
): Promise<FinancialData> {
  const periodId = opts.periodId;
  const rpcArgs: Record<string, unknown> = {};
  if (periodId) rpcArgs.p_period_id = periodId;
  if (opts.accountId) rpcArgs.p_account_id = opts.accountId;
  if (opts.from) rpcArgs.p_from = opts.from;
  if (opts.to) rpcArgs.p_to = opts.to;

  const rpcName =
    type === 'pl' ? 'report_pnl'
    : type === 'balance_sheet' ? 'report_balance_sheet'
    : type === 'cash_flow' ? 'report_cash_flow'
    : type === 'general_ledger' ? 'report_general_ledger'
    : 'report_trial_balance';

  const { data, error } = await c.database.rpc(
    rpcName,
    type === 'trial_balance' || type === 'general_ledger'
      ? rpcArgs
      : { p_period_id: periodId },
  );
  if (error || !data) throw new FunctionFailure('UNAVAILABLE', 503, true);

  let lineItems: { label: string; amount: number }[] = [];
  let totals: Record<string, number> = {};

  if (type === 'general_ledger') {
    const rows = data as Array<Record<string, unknown>>;
    lineItems = rows.map((row) => {
      const entryDate = String(row.entry_date ?? row.entryDate ?? '');
      const journalNumber = String(row.journal_number ?? row.journalNumber ?? '');
      const code = String(row.account_code ?? row.accountCode ?? '');
      const name = String(row.account_name ?? row.accountName ?? '');
      const debit = Number(row.debit ?? 0);
      const credit = Number(row.credit ?? 0);
      const side =
        debit > 0 && credit > 0
          ? `Dr ${debit} / Cr ${credit}`
          : debit > 0
            ? `Dr ${debit}`
            : `Cr ${credit}`;
      return {
        label: `${entryDate} | ${journalNumber} | ${`${code} ${name}`.trim()} | ${side}`,
        amount: Number(row.running_balance ?? row.runningBalance ?? 0),
      };
    });
    totals = {
      debit: rows.reduce((sum, row) => sum + Number(row.debit ?? 0), 0),
      credit: rows.reduce((sum, row) => sum + Number(row.credit ?? 0), 0),
    };
  } else if (type === 'trial_balance') {
    const rows = data as Array<Record<string, unknown>>;
    lineItems = rows.map((row) => ({
      label: `${row.account_code ?? row.accountCode ?? ''} ${row.account_name ?? row.accountName ?? ''}`.trim(),
      amount: Number(row.balance ?? 0),
    }));
    totals = {
      debit: rows.reduce((sum, row) => sum + Number(row.debit ?? 0), 0),
      credit: rows.reduce((sum, row) => sum + Number(row.credit ?? 0), 0),
    };
  } else {
    const json = data as { line_items: { label: string; amount: number }[]; totals: Record<string, number> };
    lineItems = json.line_items ?? [];
    totals = json.totals ?? {};
  }

  let companyId: string;
  let periodLabel: string;
  if (periodId) {
    const period = await fetchOne<{ year: number; month: number; companyId: string }>(
      c, 'fiscal_periods', periodId, 'year, month, company_id',
    );
    companyId = String(period.companyId);
    periodLabel = `${period.year}-${String(period.month).padStart(2, '0')}`;
  } else {
    const { data: memberData, error: memberError } = await c.database
      .from('company_members')
      .select('company_id')
      .eq('active', true)
      .limit(1)
      .maybeSingle();
    if (memberError || !memberData) throw new FunctionFailure('UNAVAILABLE', 503, true);
    companyId = String((memberData as { company_id?: string; companyId?: string }).company_id
      ?? (memberData as { companyId?: string }).companyId);
    const parts = [opts.from, opts.to].filter(Boolean);
    periodLabel = parts.length > 0 ? parts.join(' – ') : 'All periods';
  }

  const company = await fetchOne<{ id: string; name: string; baseCurrency: string }>(
    c, 'companies', companyId, 'id, name, base_currency',
  );

  return {
    companyId: String(company.id),
    companyName: String(company.name),
    statementType:
      type === 'pl' ? 'Profit & Loss'
      : type === 'balance_sheet' ? 'Balance Sheet'
      : type === 'cash_flow' ? 'Cash Flow'
      : type === 'general_ledger' ? 'General Ledger'
      : 'Trial Balance',
    period: periodLabel,
    currency: String(company.baseCurrency ?? 'KWD'),
    lineItems,
    totals,
  };
}

// ─── entry handler (auth, dispatch, preview/save) ───────────────────────────

const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  'Access-Control-Allow-Headers': 'Content-Type, Authorization',
};

function json(status: number, body: unknown): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...CORS, 'Content-Type': 'application/json' },
  });
}

function failure(
  status: number,
  code: string,
  requestId: string,
  retryable = false,
): Response {
  const messageKey: Record<string, string> = {
    UNAUTHENTICATED: 'errors.unauthenticated',
    VALIDATION: 'errors.validation',
    NOT_FOUND: 'errors.notFound',
    CONFLICT: 'errors.conflict',
    STORAGE_FAILED: 'errors.storageFailed',
    UNAVAILABLE: 'errors.unavailable',
    INTERNAL: 'errors.internal',
  };
  return json(status, {
    error: {
      code,
      messageKey: messageKey[code] ?? 'errors.internal',
      requestId,
      retryable,
    },
  });
}

function unauthorized(requestId: string): Response {
  return failure(401, 'UNAUTHENTICATED', requestId);
}

const DOC_TYPES = new Set(['quote', 'invoice', 'delivery', 'purchase_order', 'vendor_bill']);
const FINANCIAL_TYPES = new Set(['pl', 'balance_sheet', 'cash_flow', 'trial_balance', 'general_ledger']);

function parseRequest(value: unknown): PdfRequest | null {
  if (!value || typeof value !== 'object') return null;
  const body = value as Record<string, unknown>;
  if ((body.locale !== 'en' && body.locale !== 'ar') || (body.mode !== 'preview' && body.mode !== 'save')) {
    return null;
  }
  if (body.docType === 'financial') {
    if (typeof body.type !== 'string' || !FINANCIAL_TYPES.has(body.type)) return null;
    const periodId = body.periodId;
    const accountId = body.accountId;
    const from = body.from;
    const to = body.to;
    const hasPeriod =
      typeof periodId === 'string' && periodId.length >= 1 && periodId.length <= 160;
    const hasAccount =
      typeof accountId === 'string' && accountId.length >= 1 && accountId.length <= 160;
    const hasFrom = typeof from === 'string' && from.length >= 1 && from.length <= 32;
    const hasTo = typeof to === 'string' && to.length >= 1 && to.length <= 32;
    const hasFilters = hasAccount || hasFrom || hasTo;
    if (body.type === 'trial_balance') {
      if (!hasPeriod && !hasFilters) return null;
    } else if (!hasPeriod) {
      return null;
    }
    if (periodId !== undefined && !hasPeriod) return null;
    if (accountId !== undefined && !hasAccount) return null;
    if (from !== undefined && !hasFrom) return null;
    if (to !== undefined && !hasTo) return null;
    return {
      docType: 'financial',
      type: body.type as FinancialType,
      periodId: hasPeriod ? (periodId as string) : undefined,
      accountId: hasAccount ? (accountId as string) : undefined,
      from: hasFrom ? (from as string) : undefined,
      to: hasTo ? (to as string) : undefined,
      locale: body.locale as PdfLocale,
      mode: body.mode as PdfMode,
    };
  }
  if (
    typeof body.docType !== 'string' ||
    !DOC_TYPES.has(body.docType) ||
    typeof body.docId !== 'string' ||
    body.docId.length < 1 ||
    body.docId.length > 160
  ) return null;
  return body as DocInput;
}

function isFinancialInput(body: PdfRequest): body is FinancialInput {
  return body.docType === 'financial';
}

function stableStringify(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.entries(value as Record<string, unknown>)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, item]) => `${JSON.stringify(key)}:${stableStringify(item)}`)
      .join(',')}}`;
  }
  return JSON.stringify(value);
}

async function hashData(value: unknown): Promise<string> {
  const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(stableStringify(value)));
  return [...new Uint8Array(digest)]
    .map((byte) => byte.toString(16).padStart(2, '0'))
    .join('')
    .slice(0, 24);
}

function bytesToBase64(bytes: Uint8Array): string {
  let binary = '';
  const size = 0x8000;
  for (let i = 0; i < bytes.length; i += size) {
    binary += String.fromCharCode(...bytes.subarray(i, i + size));
  }
  return btoa(binary);
}

async function handleSave(
  c: SdkClient,
  companyId: string,
  docType: string,
  docId: string,
  locale: PdfLocale,
  state: string,
  dataHash: string,
  bytes: Uint8Array,
): Promise<PdfResponse> {
  const path = `${companyId}/${docType}/${docId}/pdf-${locale}-${state}-${TEMPLATE_VERSION.replace(':', '-')}-${dataHash}.pdf`;

  const findCached = async () => {
    const { data, error } = await c.database
      .from('attachments')
      .select('id, key')
      .eq('company_id', companyId)
      .eq('doc_type', docType)
      .eq('doc_id', docId)
      .eq('kind', 'generated_pdf')
      .eq('template_version', TEMPLATE_VERSION)
      .eq('key', path)
      .maybeSingle();
    if (error) throw new FunctionFailure('UNAVAILABLE', 503, true);
    return data as { id: string; key: string } | null;
  };
  const signedResult = async (attachment: { id: string; key: string }, cached: boolean): Promise<PdfSaveResponse> => {
    const { data: signed, error: signedError } = await c.storage
      .from('documents')
      .createSignedUrl(attachment.key, 3600);
    if (signedError || !signed) throw new FunctionFailure('STORAGE_FAILED', 502, true);
    return {
      mode: 'save',
      attachmentId: attachment.id,
      url: signed.signedUrl,
      key: attachment.key,
      cached,
    };
  };

  const existing = await findCached();
  if (existing) return signedResult(existing, true);

  const { data: up, error: upErr } = await c.storage
    .from('documents')
    .upload(path, new Blob([bytes], { type: 'application/pdf' }));
  if (upErr || !up) throw new FunctionFailure('STORAGE_FAILED', 502, true);

  if (up.key !== path) {
    for (let attempt = 0; attempt < 4; attempt += 1) {
      await new Promise((resolve) => setTimeout(resolve, 75 * (attempt + 1)));
      const winner = await findCached();
      if (winner) {
        await c.storage.from('documents').remove(up.key);
        return signedResult(winner, true);
      }
    }
    await c.storage.from('documents').remove(up.key);
    throw new FunctionFailure('CONFLICT', 409, true);
  }

  const { data: att, error: attErr } = await c.database
    .from('attachments')
    .insert([{
      company_id: companyId,
      doc_type: docType,
      doc_id: docId,
      bucket: 'documents',
      key: path,
      url: up.url,
      mime: 'application/pdf',
      size: bytes.length,
      kind: 'generated_pdf',
      template_version: TEMPLATE_VERSION,
    }])
    .select('id')
    .single();
  if (attErr || !att) {
    const winner = await findCached();
    if (winner) return signedResult(winner, true);
    throw new FunctionFailure('CONFLICT', 409, true);
  }
  return signedResult({ id: att.id, key: path }, false);
}

export default async function (req: Request): Promise<Response> {
  const requestId = crypto.randomUUID();
  const startedAt = Date.now();
  if (req.method === 'OPTIONS') {
    return new Response(null, { status: 204, headers: CORS });
  }
  if (req.method !== 'POST') {
    return failure(405, 'VALIDATION', requestId);
  }

  const auth = req.headers.get('Authorization');
  const userToken = auth?.startsWith('Bearer ') ? auth.slice(7) : null;
  if (!userToken) return unauthorized(requestId);

  let rawBody: unknown;
  try {
    rawBody = await req.json();
  } catch {
    return failure(400, 'VALIDATION', requestId);
  }
  const body = parseRequest(rawBody);
  if (!body) return failure(400, 'VALIDATION', requestId);

  const c = createClient({
    baseUrl: Deno.env.get('INSFORGE_BASE_URL'),
    accessToken: userToken,
    anonKey: Deno.env.get('ANON_KEY'),
  });

  const { data: userData } = await c.auth.getCurrentUser();
  if (!userData?.user?.id) return unauthorized(requestId);

  try {
    if (isFinancialInput(body)) {
      const data = await fetchFinancialData(c, body.type, {
        periodId: body.periodId,
        accountId: body.accountId,
        from: body.from,
        to: body.to,
      });
      const bytes = await renderFinancial(data, body.locale);
      const saveDocId =
        body.periodId ??
        `tb-${body.accountId ?? 'all'}-${body.from ?? ''}-${body.to ?? ''}`;
      if (body.mode === 'preview') {
        console.info(JSON.stringify({ requestId, function: 'pdf-gen', operation: 'preview', companyId: data.companyId, userId: userData.user.id, documentId: saveDocId, durationMs: Date.now() - startedAt, resultCode: 'OK' }));
        return json(200, { mode: 'preview', contentType: 'application/pdf', base64: bytesToBase64(bytes) });
      }
      const saved = await handleSave(c, data.companyId, 'financial', saveDocId, body.locale, 'posted', await hashData(data), bytes);
      return json(200, saved);
    }

    {
      const data = await fetchDocData(c, body.docType, body.docId);
      const bytes = await renderDoc(body.docType, data, body.locale);
      if (body.mode === 'preview') {
        console.info(JSON.stringify({ requestId, function: 'pdf-gen', operation: 'preview', companyId: data.companyId, userId: userData.user.id, documentId: body.docId, durationMs: Date.now() - startedAt, resultCode: 'OK' }));
        return json(200, { mode: 'preview', contentType: 'application/pdf', base64: bytesToBase64(bytes) });
      }
      const saved = await handleSave(c, data.companyId, body.docType, body.docId, body.locale, data.state, await hashData(data), bytes);
      console.info(JSON.stringify({ requestId, function: 'pdf-gen', operation: 'save', companyId: data.companyId, userId: userData.user.id, documentId: body.docId, durationMs: Date.now() - startedAt, cacheHit: saved.mode === 'save' ? saved.cached : false, resultCode: 'OK' }));
      return json(200, saved);
    }
  } catch (e) {
    const known = e instanceof FunctionFailure ? e : new FunctionFailure('INTERNAL', 500);
    console.error(JSON.stringify({ requestId, function: 'pdf-gen', durationMs: Date.now() - startedAt, resultCode: known.code }));
    return failure(known.status, known.code, requestId, known.retryable);
  }
}
