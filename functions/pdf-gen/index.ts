// ─── fonts (lazy per-locale) ──────────────────────────────────────────────

let fontsRegistered = false;

function ensureFontsRegistered(): void {
  if (fontsRegistered) return;
  registerFonts({
    ar: () => import('npm:pdfnative/fonts/noto-arabic-data.js'),
    latin: () => import('npm:pdfnative/fonts/noto-sans-data.js'),
  });
  fontsRegistered = true;
}

async function loadLocaleFonts(locale: PdfLocale): Promise<FontEntry[]> {
  ensureFontsRegistered();
  const latin = await loadFontData('latin');
  if (!latin) throw new Error('latin font failed to load');
  // /F1 and /F2 are reserved by pdfnative (base-14 fonts). Custom CIDFont
  // entries must use /F3+ with a leading slash, otherwise the resource name
  // is malformed and the content-stream Tf operator resolves to the reserved
  // base Helvetica (WinAnsi) — the 2-byte Identity-H GIDs are then read as
  // single-byte WinAnsi chars, shifting every ASCII glyph by −29.
  if (locale === 'en') return [{ fontData: latin, fontRef: '/F3', lang: 'latin' }];
  const ar = await loadFontData('ar');
  if (!ar) throw new Error('arabic font failed to load');
  return [
    { fontData: ar, fontRef: '/F4', lang: 'ar' },
    { fontData: latin, fontRef: '/F3', lang: 'latin' },
  ];
}

// ─── templates (block-based, black/white only) ───────────────────────────

const BW = {
  black: '#000000' as const,
  gray: '#666666' as const,
  lightBorder: '#CCCCCC' as const,
  altRow: '#F5F5F5' as const,
  white: '#FFFFFF' as const,
};

function lineItemsTable(lines: LineRow[], L: Labels, isAr: boolean): DocumentBlock {
  const headers = isAr
    ? [L.colCode, L.colDescription, L.colQty, L.colUnitPrice, L.colTotal]
    : ['Code', 'Description', 'Qty', 'Unit price', 'Total'];
  return {
    type: 'table',
    headers,
    rows: lines.map((l) => ({
      cells: [l.code, l.description, String(l.qty), String(l.unitPrice), String(l.total)],
    })),
    columns: [
      { f: 0.12, a: 'l' },
      { f: 0.40, a: 'l' },
      { f: 0.12, a: isAr ? 'r' : 'c' },
      { f: 0.18, a: 'r' },
      { f: 0.18, a: 'r' },
    ],
  };
}

function partyBlock(data: DocData, L: Labels, isAr: boolean): DocumentBlock {
  const partyLabel = data.partyType === 'supplier' ? L.supplier : L.customer;
  const dateLabel = data.dueDate ? L.dueDate : L.validUntil;
  const dateValue = data.dueDate ?? data.validUntil ?? data.date;
  const lines = [
    `${partyLabel}: ${data.partyName}`,
    data.partyVat ? `${L.currency}: ${data.currency}` : '',
    `${L.number}: ${data.number}`,
    `${L.date}: ${data.date}`,
    dateValue ? `${dateLabel}: ${dateValue}` : '',
  ].filter(Boolean);
  return {
    type: 'paragraph',
    text: lines.join('  ·  '),
    align: isAr ? 'right' : 'left',
    color: BW.gray,
  };
}

function totalsBlock(data: DocData, L: Labels, isAr: boolean): DocumentBlock {
  return {
    type: 'paragraph',
    text: [
      `${L.subtotal}: ${data.currency} ${data.subtotal}`,
      `${L.tax}: ${data.currency} ${data.taxTotal}`,
      `${L.total}: ${data.currency} ${data.total}`,
    ].join('  ·  '),
    align: isAr ? 'right' : 'left',
    color: BW.black,
  };
}

function buildDocBlocks(
  docType: string,
  data: DocData,
  L: Labels,
  locale: PdfLocale,
): DocumentBlock[] {
  const isAr = locale === 'ar';
  const title = `${docTypeLabel(docType, locale)} ${data.number}`;
  const blocks: DocumentBlock[] = [
    { type: 'heading', text: title, level: 1, color: BW.black },
    partyBlock(data, L, isAr),
    { type: 'spacer', height: 12 },
    lineItemsTable(data.lines, L, isAr),
    { type: 'spacer', height: 12 },
    totalsBlock(data, L, isAr),
  ];
  if (data.notes) blocks.push({ type: 'paragraph', text: data.notes, color: BW.gray });
  blocks.push({ type: 'paragraph', text: L.footer, color: BW.gray });
  return blocks;
}

function buildFinancialBlocks(
  data: FinancialData,
  L: Labels,
  locale: PdfLocale,
): DocumentBlock[] {
  const isAr = locale === 'ar';
  const blocks: DocumentBlock[] = [
    { type: 'heading', text: `${data.statementType} — ${data.period}`, level: 1, color: BW.black },
    {
      type: 'paragraph',
      text: `${L.currency}: ${data.currency}`,
      align: isAr ? 'right' : 'left',
      color: BW.gray,
    },
    { type: 'spacer', height: 12 },
    {
      type: 'table',
      headers: isAr ? [L.label, L.amount] : ['Label', 'Amount'],
      rows: data.lineItems.map((li) => ({ cells: [li.label, String(li.amount)] })),
      columns: [
        { f: 0.6, a: 'l' },
        { f: 0.4, a: 'r' },
      ],
    },
    { type: 'spacer', height: 12 },
    {
      type: 'paragraph',
      text: Object.entries(data.totals)
        .map(([k, v]) => `${k}: ${data.currency} ${v}`)
        .join('  ·  '),
      align: isAr ? 'right' : 'left',
      color: BW.black,
    },
    { type: 'paragraph', text: L.footer, color: BW.gray },
  ];
  return blocks;
}

