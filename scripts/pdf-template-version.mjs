import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const functionPath = resolve(root, "functions/pdf-gen/index.ts");
const messagePaths = [
  resolve(root, "messages/en.json"),
  resolve(root, "messages/ar.json"),
];
const marker =
  /const TEMPLATE_VERSION = 'sha256:[0-9a-f]{16}'; \/\/ generated by scripts\/pdf-template-version\.mjs/;

const source = await readFile(functionPath, "utf8");
const normalized = source.replace(
  marker,
  "const TEMPLATE_VERSION = 'sha256:GENERATED'; // generated by scripts/pdf-template-version.mjs",
);
const labels = await Promise.all(messagePaths.map((path) => readFile(path, "utf8")));
const digest = createHash("sha256")
  .update(normalized)
  .update(labels.join("\n"))
  .digest("hex")
  .slice(0, 16);
const replacement = `const TEMPLATE_VERSION = 'sha256:${digest}'; // generated by scripts/pdf-template-version.mjs`;

if (!marker.test(source)) {
  throw new Error("pdf-gen TEMPLATE_VERSION marker was not found");
}
await writeFile(functionPath, source.replace(marker, replacement));
console.log(`pdf template version: sha256:${digest}`);
