function docTypeLabel(docType: string, locale: PdfLocale): string {
  const map: Record<string, string> = {
    quote: labelsFor(locale).docType,
    invoice: locale === "ar" ? "فاتورة" : "Invoice",
    delivery: locale === "ar" ? "إشعار تسليم" : "Delivery note",
    purchase_order: locale === "ar" ? "أمر شراء" : "Purchase order",
    vendor_bill: locale === "ar" ? "فاتورة المورد" : "Vendor bill",
    financial: locale === "ar" ? "القوائم المالية" : "Financial statement",
  };
  return map[docType] ?? labelsFor(locale).docType;
}

// ─── fonts (lazy per-locale; pdfnative bundled Noto data) ─────────────────

let fontsRegistered = false;

async function importFontModule(
  loader: () => Promise<Record<string, unknown>>,
): Promise<FontData> {
  const mod = await loader();
  // Named-export font modules are FontData-shaped; cast past .d.ts drift on markAnchors.
  return mod as unknown as FontData;
}

function ensureFontsRegistered(): void {
  if (fontsRegistered) return;
  const ar: FontLoader = () =>
    importFontModule(() => import("pdfnative/fonts/noto-arabic-data.js"));
  const latin: FontLoader = () =>
    importFontModule(() => import("pdfnative/fonts/noto-sans-data.js"));
  registerFonts({ ar, latin });
  fontsRegistered = true;
}

async function loadLocaleFonts(locale: PdfLocale): Promise<FontEntry[]> {
  ensureFontsRegistered();
  const latin = await loadFontData("latin");
  if (!latin) throw new Error("latin font failed to load");
  // /F1 and /F2 are reserved by pdfnative (base-14 fonts). Custom CIDFont
  // entries must use /F3+ with a leading slash.
  if (locale === "en") return [{ fontData: latin, fontRef: "/F3", lang: "latin" }];
  const ar = await loadFontData("ar");
  if (!ar) throw new Error("arabic font failed to load");
  return [
    { fontData: ar, fontRef: "/F4", lang: "ar" },
    { fontData: latin, fontRef: "/F3", lang: "latin" },
  ];
}

const BW = {
  black: "#000000" as const,
  gray: "#666666" as const,
  lightBorder: "#CCCCCC" as const,
  altRow: "#F5F5F5" as const,
  white: "#FFFFFF" as const,
};

function lineItemsTable(lines: LineRow[], L: Labels, isAr: boolean): DocumentBlock {
  const headers = isAr
    ? [L.colCode, L.colDescription, L.colQty, L.colUnitPrice, L.colTotal]
    : ["Code", "Description", "Qty", "Unit price", "Total"];
  return {
    type: "table",
    headers,
    rows: lines.map((l) => ({
      cells: [l.code, l.description, String(l.qty), String(l.unitPrice), String(l.total)],
      type: "",
      pointed: false,
    })),
    columns: [
      { f: 0.12, a: "l", mx: 24, mxH: 24 },
      { f: 0.4, a: "l", mx: 80, mxH: 24 },
      { f: 0.12, a: isAr ? "r" : "c", mx: 16, mxH: 16 },
      { f: 0.18, a: "r", mx: 24, mxH: 24 },
      { f: 0.18, a: "r", mx: 24, mxH: 24 },
    ],
  };
}

function partyBlock(data: DocData, L: Labels, isAr: boolean): DocumentBlock {
  const partyLabel = data.partyType === "supplier" ? L.supplier : L.customer;
  const dateLabel = data.dueDate ? L.dueDate : L.validUntil;
  const dateValue = data.dueDate ?? data.validUntil ?? data.date;
  const lines = [
    `${partyLabel}: ${data.partyName}`,
    data.partyVat ? `${L.currency}: ${data.currency}` : "",
    `${L.number}: ${data.number}`,
    `${L.date}: ${data.date}`,
    dateValue ? `${dateLabel}: ${dateValue}` : "",
  ].filter(Boolean);
  return {
    type: "paragraph",
    text: lines.join("  ·  "),
    align: isAr ? "right" : "left",
    color: BW.gray,
  };
}

function totalsBlock(data: DocData, L: Labels, isAr: boolean): DocumentBlock {
  return {
    type: "paragraph",
    text: [
      `${L.subtotal}: ${data.currency} ${data.subtotal}`,
      `${L.tax}: ${data.currency} ${data.taxTotal}`,
      `${L.total}: ${data.currency} ${data.total}`,
    ].join("  ·  "),
    align: isAr ? "right" : "left",
    color: BW.black,
  };
}

function buildDocBlocks(
  docType: string,
  data: DocData,
  L: Labels,
  locale: PdfLocale,
): DocumentBlock[] {
  const isAr = locale === "ar";
  const title = `${docTypeLabel(docType, locale)} ${data.number}`;
  const blocks: DocumentBlock[] = [
    { type: "heading", text: title, level: 1, color: BW.black },
    partyBlock(data, L, isAr),
    { type: "spacer", height: 12 },
    lineItemsTable(data.lines, L, isAr),
    { type: "spacer", height: 12 },
    totalsBlock(data, L, isAr),
  ];
  if (data.notes) blocks.push({ type: "paragraph", text: data.notes, color: BW.gray });
  blocks.push({ type: "paragraph", text: L.footer, color: BW.gray });
  return blocks;
}

function buildFinancialBlocks(
  data: FinancialData,
  L: Labels,
  locale: PdfLocale,
): DocumentBlock[] {
  const isAr = locale === "ar";
  return [
    { type: "heading", text: `${data.statementType} — ${data.period}`, level: 1, color: BW.black },
    {
      type: "paragraph",
      text: `${L.currency}: ${data.currency}`,
      align: isAr ? "right" : "left",
      color: BW.gray,
    },
    { type: "spacer", height: 12 },
    {
      type: "table",
      headers: isAr ? [L.label, L.amount] : ["Label", "Amount"],
      rows: data.lineItems.map((li) => ({
        cells: [li.label, String(li.amount)],
        type: "",
        pointed: false,
      })),
      columns: [
        { f: 0.6, a: "l", mx: 80, mxH: 24 },
        { f: 0.4, a: "r", mx: 32, mxH: 24 },
      ],
    },
    { type: "spacer", height: 12 },
    {
      type: "paragraph",
      text: Object.entries(data.totals)
        .map(([k, v]) => `${k}: ${data.currency} ${v}`)
        .join("  ·  "),
      align: isAr ? "right" : "left",
      color: BW.black,
    },
    { type: "paragraph", text: L.footer, color: BW.gray },
  ];
}

const TEMPLATE_VERSION = "sha256:9fa58346c397f250";

const BW_COLORS = {
  title: BW.black,
  credit: BW.black,
  debit: BW.black,
  text: BW.black,
  thBg: BW.white,
  thBrd: BW.black,
  rowBrd: BW.lightBorder,
  ptdBg: BW.white,
  balBg: BW.altRow,
  balBrd: BW.black,
  label: BW.gray,
  footer: BW.gray,
};

function pageHeader(title: string, companyName: string, isAr: boolean) {
  return {
    left: isAr ? "" : companyName,
    center: "",
    right: isAr ? companyName : title,
  };
}

function pageFooter(footerText: string) {
  return { left: footerText, right: "Page {page} of {pages}" };
}

async function renderDoc(docType: string, data: DocData, locale: PdfLocale): Promise<Uint8Array> {
  const L = labelsFor(locale);
  const isAr = locale === "ar";
  const title = `${docTypeLabel(docType, locale)} ${data.number}`;
  const blocks = buildDocBlocks(docType, data, L, locale);
  const fontEntries = await loadLocaleFonts(locale);
  const layout: Partial<PdfLayoutOptions> = {
    tagged: "pdfa2b",
    colors: BW_COLORS,
    headerTemplate: pageHeader(title, data.companyName, isAr),
    footerTemplate: pageFooter(L.footer),
    viewerPreferences: { direction: isAr ? "r2l" : "l2r" },
  };
  return buildDocumentPDFBytes(
    { title, blocks, footerText: L.footer, fontEntries },
    layout,
  );
}

async function renderFinancial(data: FinancialData, locale: PdfLocale): Promise<Uint8Array> {
  const L = labelsFor(locale);
  const isAr = locale === "ar";
  const title = `${data.statementType} — ${data.period}`;
  const blocks = buildFinancialBlocks(data, L, locale);
  const fontEntries = await loadLocaleFonts(locale);
  const layout: Partial<PdfLayoutOptions> = {
    tagged: "pdfa2b",
    colors: BW_COLORS,
    headerTemplate: pageHeader(title, data.companyName, isAr),
    footerTemplate: pageFooter(L.footer),
    viewerPreferences: { direction: isAr ? "r2l" : "l2r" },
  };
  return buildDocumentPDFBytes(
    { title, blocks, footerText: L.footer, fontEntries },
    layout,
  );
}

export class PdfServiceError extends Error {
  constructor(
    readonly code: Extract<
      ActionErrorCode,
      "NOT_FOUND" | "CONFLICT" | "STORAGE_FAILED" | "UNAVAILABLE" | "INTERNAL" | "UNAUTHENTICATED" | "VALIDATION"
    >,
    readonly status: number,
    readonly retryable = false,
  ) {
    super(code);
    this.name = "PdfServiceError";
  }
}

function camelize<T = Record<string, unknown>>(row: T): T {
  const out: Record<string, unknown> = {};
  for (const k of Object.keys(row as object)) {
    const camel = k.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
    out[camel] = (row as Record<string, unknown>)[k];
  }
  return out as T;
}

async function fetchOne<T = Record<string, unknown>>(
  c: PdfClient,
  table: string,
  id: string,
  select: string,
): Promise<T> {
  const { data, error } = await c.database.from(table).select(select).eq("id", id).single();
  if (error || !data) throw new PdfServiceError("NOT_FOUND", 404);
  return camelize(data as T);
}

async function fetchLines(
  c: PdfClient,
  lineTable: string,
  parentCol: string,
  docId: string,
): Promise<LineRow[]> {
  const { data, error } = await c.database
    .from(lineTable)
    .select("product_id, description, qty, qty_delivered, unit_price")
    .eq(parentCol, docId);
  if (error) throw new PdfServiceError("UNAVAILABLE", 503, true);
  const rows = (data ?? []) as Record<string, unknown>[];
  const productIds = [
    ...new Set(rows.map((row) => String(row.product_id ?? "")).filter(Boolean)),
  ];
  const productMap = new Map<string, { sku?: string; name?: string }>();
  if (productIds.length > 0) {
    const { data: products, error: productError } = await c.database
      .from("products")
      .select("id, sku, name")
      .in("id", productIds);
    if (productError) throw new PdfServiceError("UNAVAILABLE", 503, true);
    for (const product of products ?? []) {
      productMap.set(String((product as { id: string }).id), product as { sku?: string; name?: string });
    }
  }
  return rows.map((r) => {
    const row = camelize(r);
    const product = productMap.get(String(row.productId ?? ""));
    const qty = Number(row.qtyDelivered ?? row.qty ?? 0);
    const unitPrice = Number(row.unitPrice ?? 0);
    return {
      code: String(product?.sku ?? ""),
      description: String(row.description ?? product?.name ?? ""),
      qty,
      unitPrice,
      total: Number((Number(row.total ?? qty * unitPrice)).toFixed(3)),
    };
  });
}

