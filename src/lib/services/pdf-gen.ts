async function fetchDocData(
  c: PdfClient,
  docType: PdfDocType,
  docId: string,
): Promise<DocData> {
  const doc = await fetchOne<Record<string, unknown>>(c, DOC_TABLEL[docType], docId, "*");

  const [party, company, lines] = await Promise.all([
    fetchOne<Record<string, unknown>>(
      c,
      PARTY_TABLEL[docType],
      String(doc.customerId ?? doc.supplierId ?? ""),
      "id, name, vat_number",
    ),
    fetchOne<Record<string, unknown>>(
      c,
      "companies",
      String(doc.companyId ?? ""),
      "id, name, vat_number, base_currency",
    ),
    fetchLines(c, LINE_TABLEL[docType], LINE_PARENT_COL[docType], docId),
  ]);

  return {
    companyId: String(company.id ?? ""),
    number: String(doc.number ?? ""),
    date: String(doc.date ?? ""),
    dueDate: doc.dueDate ? String(doc.dueDate) : undefined,
    validUntil: doc.validUntil ? String(doc.validUntil) : undefined,
    partyType: PARTY_TABLEL[docType] === "suppliers" ? "supplier" : "customer",
    partyName: String(party.name ?? ""),
    partyVat: party.vatNumber ? String(party.vatNumber) : undefined,
    companyName: String(company.name ?? ""),
    companyVat: company.vatNumber ? String(company.vatNumber) : undefined,
    currency: String(doc.currency ?? company.baseCurrency ?? "KWD"),
    lines,
    subtotal: Number(doc.subtotal ?? 0),
    taxTotal: Number(doc.taxTotal ?? 0),
    total: Number(doc.total ?? 0),
    notes: doc.notes ? String(doc.notes) : undefined,
    state: String(doc.state ?? "draft"),
  };
}

async function fetchFinancialData(
  c: PdfClient,
  type: FinancialType,
  periodId: string,
): Promise<FinancialData> {
  const rpcName =
    type === "pl"
      ? "report_pnl"
      : type === "balance_sheet"
        ? "report_balance_sheet"
        : type === "cash_flow"
          ? "report_cash_flow"
          : "report_trial_balance";
  const { data, error } =
    type === "trial_balance"
      ? await c.database.rpc(rpcName)
      : await c.database.rpc(rpcName, { p_period_id: periodId });
  if (error || !data) throw new PdfServiceError("UNAVAILABLE", 503, true);

  const json =
    type === "trial_balance"
      ? {
          line_items: (data as Array<Record<string, unknown>>).map((row) => ({
            label: `${row.account_code ?? ""} ${row.account_name ?? ""}`.trim(),
            amount: Number(row.balance ?? 0),
          })),
          totals: {
            debit: (data as Array<Record<string, unknown>>).reduce(
              (sum, row) => sum + Number(row.debit ?? 0),
              0,
            ),
            credit: (data as Array<Record<string, unknown>>).reduce(
              (sum, row) => sum + Number(row.credit ?? 0),
              0,
            ),
          },
        }
      : (data as {
          line_items: { label: string; amount: number }[];
          totals: Record<string, number>;
        });

  const period = await fetchOne<{ year: number; month: number; companyId: string }>(
    c,
    "fiscal_periods",
    periodId,
    "year, month, company_id",
  );
  const company = await fetchOne<{ id: string; name: string; baseCurrency: string }>(
    c,
    "companies",
    period.companyId,
    "id, name, base_currency",
  );

  return {
    companyId: String(company.id),
    companyName: String(company.name),
    statementType:
      type === "pl"
        ? "Profit & Loss"
        : type === "balance_sheet"
          ? "Balance Sheet"
          : type === "cash_flow"
            ? "Cash Flow"
            : "Trial Balance",
    period: `${period.year}-${String(period.month).padStart(2, "0")}`,
    currency: String(company.baseCurrency ?? "KWD"),
    lineItems: json.line_items ?? [],
    totals: json.totals ?? {},
  };
}

function stableStringify(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.entries(value as Record<string, unknown>)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, item]) => `${JSON.stringify(key)}:${stableStringify(item)}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

async function hashData(value: unknown): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(stableStringify(value)),
  );
  return [...new Uint8Array(digest)]
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("")
    .slice(0, 24);
}

function bytesToBase64(bytes: Uint8Array): string {
  return Buffer.from(bytes).toString("base64");
}

async function handleSave(
  c: PdfClient,
  companyId: string,
  docType: string,
  docId: string,
  locale: PdfLocale,
  state: string,
  dataHash: string,
  bytes: Uint8Array,
): Promise<Extract<PdfResult, { mode: "save" }>> {
  const path = `${companyId}/${docType}/${docId}/pdf-${locale}-${state}-${TEMPLATE_VERSION.replace(":", "-")}-${dataHash}.pdf`;

  const findCached = async () => {
    const { data, error } = await c.database
      .from("attachments")
      .select("id, key")
      .eq("company_id", companyId)
      .eq("doc_type", docType)
      .eq("doc_id", docId)
      .eq("kind", "generated_pdf")
      .eq("template_version", TEMPLATE_VERSION)
      .eq("key", path)
      .maybeSingle();
    if (error) throw new PdfServiceError("UNAVAILABLE", 503, true);
    return data as { id: string; key: string } | null;
  };

  const signedResult = async (
    attachment: { id: string; key: string },
    cached: boolean,
  ): Promise<Extract<PdfResult, { mode: "save" }>> => {
    const { data: signed, error: signedError } = await c.storage
      .from("documents")
      .createSignedUrl(attachment.key, 3600);
    if (signedError || !signed) throw new PdfServiceError("STORAGE_FAILED", 502, true);
    return {
      mode: "save",
      attachmentId: attachment.id,
      url: signed.signedUrl,
      key: attachment.key,
      cached,
    };
  };

  const existing = await findCached();
  if (existing) return signedResult(existing, true);

  const { data: up, error: upErr } = await c.storage
    .from("documents")
    .upload(path, new Blob([Buffer.from(bytes)], { type: "application/pdf" }));
  if (upErr || !up) throw new PdfServiceError("STORAGE_FAILED", 502, true);

  if (up.key !== path) {
    for (let attempt = 0; attempt < 4; attempt += 1) {
      await new Promise((resolve) => setTimeout(resolve, 75 * (attempt + 1)));
      const winner = await findCached();
      if (winner) {
        await c.storage.from("documents").remove(up.key);
        return signedResult(winner, true);
      }
    }
    await c.storage.from("documents").remove(up.key);
    throw new PdfServiceError("CONFLICT", 409, true);
  }

  const { data: att, error: attErr } = await c.database
    .from("attachments")
    .insert([
      {
        company_id: companyId,
        doc_type: docType,
        doc_id: docId,
        bucket: "documents",
        key: path,
        url: up.url,
        mime: "application/pdf",
        size: bytes.length,
        kind: "generated_pdf",
        template_version: TEMPLATE_VERSION,
      },
    ])
    .select("id")
    .single();
  if (attErr || !att) {
    const winner = await findCached();
    if (winner) return signedResult(winner, true);
    throw new PdfServiceError("CONFLICT", 409, true);
  }
  return signedResult({ id: (att as { id: string }).id, key: path }, false);
}

